{-# LANGUAGE OverloadedStrings #-}

{- | CSV files -> Faust rewrite. In a piece, you can do

> spec = library("data/spectrum.csv");

and fau will rewrite it into a @.lib@ file where each
column is a list which you can @ba.take@
-}
module Fau.Csv (
    csvToLib,
    csvImports,
)
where

import Control.Monad (unless, when, zipWithM_)
import Data.Char (isAsciiLower, isAsciiUpper, isDigit)
import Data.List (nub, transpose)
import Data.Text (Text)
import Data.Text qualified as T
import Fau.Params (parseNumber, showNumber)

-- | Faust definitions for the columns of a CSV file.
csvToLib :: FilePath -> Text -> Either String Text
csvToLib path csv = do
    let rows = [(n, l) | (n, l) <- zip [1 :: Int ..] (map T.strip (T.lines csv)), not (T.null l)]
    ((_, header), body) <- case rows of
        h : b@(_ : _) -> Right (h, b)
        _ -> Left (path <> ": needs a row of column names and at least one row of numbers")
    let names = map T.strip (T.splitOn "," (T.stripStart (T.dropWhile (== '#') header)))
    zipWithM_ (checkName path) [1 :: Int ..] names
    when (nub names /= names) $ Left (path <> ": two columns have the same name")
    values <- traverse (row (length names)) body
    pure . T.unlines $
        ("// generated by fau from " <> T.pack path)
            : [name <> " = (" <> T.intercalate ", " (map (T.pack . showNumber) column) <> ");" | (name, column) <- zip names (transpose values)]
  where
    row width (n, l) = do
        let cells = map T.strip (T.splitOn "," l)
        unless (length cells == width) $
            Left (path <> ":" <> show n <> ": " <> show (length cells) <> " values, but " <> show width <> " columns")
        traverse (cell n) cells
    cell n c = maybe (Left (path <> ":" <> show n <> ": not a number: " <> T.unpack c)) Right (parseNumber c)

checkName :: FilePath -> Int -> Text -> Either String ()
checkName path i name
    | T.null name = Left (path <> ": column " <> show i <> " has no name (a pandas index? write the file with index=False)")
    | valid = Right ()
    | otherwise = Left (path <> ": column name " <> T.unpack name <> " isn't a Faust identifier")
  where
    valid = case T.uncons name of
        Just (c, rest) -> isStart c && T.all (\x -> isStart x || isDigit x) rest
        Nothing -> False
    isStart c = isAsciiLower c || isAsciiUpper c || c == '_'

csvImports :: Text -> [Text]
csvImports src =
    nub [path | chunk <- drop 1 (T.splitOn "library(\"" src), let path = T.takeWhile (/= '"') chunk, ".csv" `T.isSuffixOf` path]
